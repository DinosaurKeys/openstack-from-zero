#!/usr/bin/env python3
"""Create the agreed Kolla inventory and verify node access; default plan only."""
import sys
sys.dont_write_bytecode = True
import argparse
import datetime as dt
import importlib.util
import json
import os
from pathlib import Path
import re
import shlex
import stat
import subprocess
import tempfile

SPEC = importlib.util.spec_from_file_location('lab_tools', Path(__file__).with_name('phase2-install-tools.py'))
tools = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(tools)
REPO = Path(__file__).resolve().parents[1]
ENV = Path('/home/joe/venvs/kolla')
NODES = {'node1': '192.168.0.200', 'node2': '192.168.0.201', 'node3': '192.168.0.202'}
KEY = Path('/home/joe/.ssh/openstack-from-zero')


def private_dir(path):
    for p in [path, *path.parents]:
        if p.is_symlink():
            raise RuntimeError('Refuse symlinked working path: ' + str(p))
    path.mkdir(parents=True, mode=0o700, exist_ok=True)
    if path.stat().st_uid != os.getuid():
        raise RuntimeError('Working directory must belong to joe')
    path.chmod(0o700)


def preserve_write(path, text):
    if path.is_symlink() or (path.exists() and path.read_text() != text):
        raise RuntimeError('Existing file differs; preserved without overwrite: ' + str(path))
    if not path.exists():
        with path.open('x') as output:
            output.write(text)
    path.chmod(0o600)


def render_inventory(template, computes=None):
    groups = {
        'control': '\n'.join(f'{name} ansible_host={ip}' for name, ip in NODES.items()),
        'network': '\n'.join(NODES),
        'compute': '\n'.join(NODES if computes is None else computes),
        'monitoring': '# Placement deferred to the monitoring phase.',
        'storage': '\n'.join(NODES),
        'deployment': 'localhost ansible_connection=local ansible_python_interpreter=' + str(ENV/'bin/python'),
    }
    for group, content in groups.items():
        pattern = r'(?ms)^\[' + re.escape(group) + r'\]\n.*?(?=^\[|\Z)'
        template, count = re.subn(pattern, lambda m: '['+group+']\n'+content+'\n\n', template)
        if count != 1:
            raise RuntimeError('Unexpected installed inventory group: ' + group)
    return ('# Generated by openstack-from-zero Phase 2 Chapter D.\n' + template.rstrip() +
            '\n\n[baremetal:vars]\nansible_user=joe\nansible_connection=ssh\n'
            'ansible_python_interpreter=/usr/bin/python3\n'
            'ansible_ssh_private_key_file=' + str(KEY) + '\n'
            'ansible_ssh_common_args=-o IdentitiesOnly=yes -o StrictHostKeyChecking=yes -o BatchMode=yes\n'
            'ansible_become_method=sudo\nansible_become_user=root\n')


def hosts_under(data, group):
    result = set(data.get(group, {}).get('hosts', []))
    for child in data.get(group, {}).get('children', []):
        result |= hosts_under(data, child)
    return result


def validate_inventory(data):
    three = set(NODES)
    expected = {'control': three, 'network': three, 'compute': three,
                'storage': three, 'baremetal': three, 'deployment': {'localhost'},
                'cinder-volume': three, 'cinder-volume-lvm': three, 'monitoring': set()}
    for group, hosts in expected.items():
        if hosts_under(data, group) != hosts:
            raise RuntimeError('Unexpected hosts in group ' + group)
    if hosts_under(data, 'all') != three | {'localhost'}:
        raise RuntimeError('Unexpected inventory host outside the agreed lab')
    for name, ip in NODES.items():
        values = data['_meta']['hostvars'][name]
        if any(values.get(k) != v for k, v in {
            'ansible_host': ip, 'ansible_user': 'joe',
            'ansible_ssh_private_key_file': str(KEY),
            'ansible_python_interpreter': '/usr/bin/python3'}.items()):
            raise RuntimeError('Connection settings differ for ' + name)


def access_playbook():
    # JSON is valid YAML; generate data without string-templating shell commands.
    return json.dumps([{'name': 'Chapter D identity, Python and sudo checks',
        'hosts': 'baremetal', 'gather_facts': False, 'become': False,
        'tasks': [
            {'name': 'Check SSH and Python access (Ansible ping)', 'ansible.builtin.ping': {}},
            {'name': 'Read hostname', 'ansible.builtin.command': {'argv': ['/usr/bin/hostname', '-s']}, 'register': 'lab_hostname', 'changed_when': False},
            {'name': 'Read login account', 'ansible.builtin.command': {'argv': ['/usr/bin/id', '-un']}, 'register': 'lab_user', 'changed_when': False},
            {'name': 'Read IPv4 addresses', 'ansible.builtin.command': {'argv': ['/usr/sbin/ip', '-j', '-4', 'address', 'show']}, 'register': 'lab_ip', 'changed_when': False},
            {'name': 'Confirm intended node and login', 'ansible.builtin.assert': {'that': [
                'lab_hostname.stdout == inventory_hostname', "lab_user.stdout == 'joe'",
                "ansible_host in (lab_ip.stdout | from_json | map(attribute='addr_info') | flatten | map(attribute='local') | list)"], 'success_msg': 'Expected node identity and management IPv4 confirmed'}},
            {'name': 'Read effective UID through sudo', 'ansible.builtin.command': {'argv': ['/usr/bin/id', '-u']}, 'become': True, 'register': 'lab_root', 'changed_when': False},
            {'name': 'Confirm sudo access', 'ansible.builtin.assert': {'that': ["lab_root.stdout == '0'"], 'success_msg': 'Sudo root access confirmed'}}
        ]}], indent=2) + '\n'


def ensure_agent(env, log):
    for path in (KEY, Path(str(KEY)+'.pub')):
        if path.is_symlink() or not path.is_file() or path.stat().st_uid != os.getuid():
            raise RuntimeError('Expected existing joe-owned key file: ' + str(path))
    if stat.S_IMODE(KEY.stat().st_mode) & 0o077:
        raise RuntimeError('Private key permissions allow other users; review before proceeding')
    probe = subprocess.run(['ssh-add', '-l'], env=env, capture_output=True)
    if probe.returncode not in (0, 1):
        started = subprocess.run(['ssh-agent', '-s'], env=env, text=True, capture_output=True, check=True).stdout
        for name in ('SSH_AUTH_SOCK', 'SSH_AGENT_PID'):
            match = re.search(r'\b'+name+r'=([^;\n]+);', started)
            if not match:
                raise RuntimeError('Could not initialize SSH agent')
            env[name] = match.group(1)
        log('Started an SSH agent for this script. No new keys were created.')
    test = subprocess.run(['ssh-add', '-T', str(KEY)+'.pub'], env=env, capture_output=True)
    if test.returncode:
        log('Enter the existing SSH-key passphrase if asked (not a node sudo password).')
        subprocess.run(['ssh-add', '-t', '14400', str(KEY)], env=env, check=True)
        subprocess.run(['ssh-add', '-T', str(KEY)+'.pub'], env=env, check=True)
    log('Existing selected SSH key is available to the agent. Agent lifetime is not extended if already loaded.')


def inventory_data(env, inventory, log):
    args = [str(ENV/'bin/ansible-inventory'), '-i', str(inventory), '--list']
    log('$ ' + shlex.join(args))
    result = subprocess.run(args, env=env, text=True, capture_output=True, timeout=30)
    if result.stderr.strip():
        log(result.stderr.rstrip())
    if result.returncode:
        raise RuntimeError('Inventory parsing failed: ' + result.stdout + result.stderr)
    # Kolla has hyphenated groups; Ansible may warn on stderr. Keep JSON separate.
    return json.loads(result.stdout)


def execute(log, transcript=None):
    env = tools.tool_environment()
    if transcript is not None:
        env['ANSIBLE_LOG_PATH'] = str(transcript)
    run = tools.Runner(log, env)
    versions = json.loads(run.run([ENV/'bin/python', '-c',
        "import importlib.metadata as m,json; print(json.dumps({'kolla':m.version('kolla-ansible'),'ansible':m.version('ansible-core')}))"]))
    if versions != {'kolla': '23.0.0', 'ansible': '2.21.5'}:
        raise RuntimeError('Expected the agreed installed tool versions')
    template = ENV/'share/kolla-ansible/ansible/inventory/multinode'
    folder = REPO/'private/phase2'
    private_dir(folder)
    inventory = folder/'inventory.ini'
    playbook = folder/'check-access.yml'
    preserve_write(inventory, render_inventory(template.read_text()))
    preserve_write(playbook, access_playbook())
    log('Private inventory: ' + str(inventory))
    parsed = inventory_data(env, inventory, log)
    validate_inventory(parsed)
    for group in ('control', 'network', 'compute', 'storage', 'deployment'):
        log(group + ': ' + ', '.join(sorted(hosts_under(parsed, group))))
    run.run([ENV/'bin/ansible-playbook', '-i', inventory, playbook, '--syntax-check'])
    log('RESULT: INVENTORY_LAYOUT_OK (local parsing only; live checks follow)')
    ensure_agent(env, log)
    for name, ip in NODES.items():
        log('Node: '+name+' ('+ip+'). BECOME password = joe sudo password on this node.')
        # Password input is handled by Ansible, never captured by the report.
        run.run([ENV/'bin/ansible-playbook', '-i', inventory, playbook,
                 '--limit', name, '--ask-become-pass'], terminal=True)
        log('NODE_ACCESS_OK ' + name)
    log('RESULT: INVENTORY_ACCESS_READY for all')
    log('No packages, services, network, disks, SSH keys or sudo policy changed.')


def add_node1_compute(log):
    env = tools.tool_environment()
    folder = REPO/'private/phase2'
    private_dir(folder)
    inventory = folder/'inventory.ini'
    template = (ENV/'share/kolla-ansible/ansible/inventory/multinode').read_text()
    desired = render_inventory(template)
    previous = render_inventory(template, computes=('node2', 'node3'))
    if inventory.is_symlink() or not inventory.is_file():
        raise RuntimeError('Expected the existing private inventory from Chapter D')
    original = inventory.read_text()
    if original not in (previous, desired):
        raise RuntimeError('Inventory has other edits; preserved without overwrite')
    if original == desired:
        validate_inventory(inventory_data(env, inventory, log))
        log('Compute already includes node1, node2 and node3; no file change needed.')
    else:
        fd, candidate_name = tempfile.mkstemp(prefix='inventory-candidate-', suffix='.ini', dir=folder)
        candidate = Path(candidate_name)
        try:
            with os.fdopen(fd, 'w') as output:
                output.write(desired)
            validate_inventory(inventory_data(env, candidate, log))
            fd, backup_name = tempfile.mkstemp(prefix='inventory-before-add-node1-', suffix='.ini', dir=folder)
            with os.fdopen(fd, 'w') as backup:
                backup.write(original)
            log('Private backup: ' + backup_name)
            if inventory.is_symlink() or inventory.read_text() != original:
                raise RuntimeError('Inventory changed during validation; left unchanged')
            os.replace(candidate, inventory)
        finally:
            if candidate.exists():
                candidate.unlink()
    log('compute: node1, node2, node3')
    log('RESULT: COMPUTE_ROLES_UPDATED')
    log('Local inventory only; no SSH, sudo, packages or running services changed.')


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument('--add-node1-compute', action='store_true', help='back up and update only the known earlier inventory; no node connections')
    modes.add_argument('--apply', action='store_true', help='write private inventory and perform explained access checks')
    args = parser.parse_args(argv)
    tools.guard()
    if not args.apply and not args.add_node1_compute:
        print('PLAN ONLY: control/network/storage=node1,node2,node3; compute=node1,node2,node3.')
        print('Use existing joe SSH key. Write private inventory; check identities, Python and sudo per node.')
        print('No changes made. Read Phase 2 Chapter D before --apply.')
        return 0
    if args.apply and not sys.stdin.isatty():
        raise RuntimeError('Use an interactive terminal for SSH-key and sudo prompts')
    os.umask(0o077)
    reports = REPO/'reports'
    private_dir(reports)
    stamp = dt.datetime.now(dt.timezone.utc).strftime('%Y%m%dT%H%M%SZ-')
    fd, filename = tempfile.mkstemp(prefix='phase2-inventory-'+stamp, suffix='.txt', dir=reports)
    with os.fdopen(fd, 'w') as output:
        def log(line):
            print(line, flush=True); output.write(line+'\n'); output.flush()
        log('Phase 2 — Chapter D: private inventory + node identity, Python and sudo checks')
        log('Ansible prompt/task output stays in terminal; per-node exit status and checkpoints are recorded.')
        try:
            if args.add_node1_compute:
                log('Mode: add node1 compute in the existing inventory; local validation only.')
                add_node1_compute(log)
            else:
                transcript = Path(filename).with_suffix('.ansible.log')
                execute(log, transcript)
            status = 0
        except (OSError, RuntimeError, ValueError, KeyError, subprocess.CalledProcessError, subprocess.TimeoutExpired, KeyboardInterrupt) as error:
            log('Stopped: '+str(error)); log('RESULT: INVENTORY_ACCESS_NEEDS_REVIEW')
            status = 1
        finally:
            if 'transcript' in locals() and transcript.is_file():
                log('\nAnsible task output (password input is not logged):')
                log(transcript.read_text())
    print('Private report: '+filename)
    print('Read it with: cat '+shlex.quote(filename))
    return status


if __name__ == '__main__':
    try:
        sys.exit(main())
    except (OSError, RuntimeError, ValueError) as error:
        print('Stopped: '+str(error), file=sys.stderr); sys.exit(1)
